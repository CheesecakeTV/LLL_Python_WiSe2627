
x = 5
y = 7
z = 9

# x ist größer als y
print(x > y)

# x ist größer als y und kleiner als z
print(x > y and x < z)

# x ist durch y teilbar
print(x % y == 0)

# x ist größer als y, oder x ist kleiner als y
print(x != y)

# x ist nicht gleich 0
print(x != 0)
print(bool(x))

# x ist um maximal 5 zum Wert von y unterschiedlich
print(abs(x - y) <= 5)


