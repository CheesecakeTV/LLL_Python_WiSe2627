# int zu bool
# immer erlaubt
print(bool(5))
print(bool(0))  # False
print(bool(-1))

# bool zu int
# Immer erlaubt
print(int(True))
print(int(False))

# str zu bool
# Immer erlaubt
print(bool("Test"))
print(bool("")) # False
print(bool(" "))

# bool zu str
print(str(True))
print(str(False))

# None zu bool
print(bool(None))

# None zu int
print(int(None))

